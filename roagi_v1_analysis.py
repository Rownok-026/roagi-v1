def W_daily(C, weights, vort_mode="abs", rows=None):
    """C: dict of (nt, n_ocean) normalized components.
    weights: length-5 array for [vort, conv, sst, sst_grad, precip].
    rows: optional index of days. Returns W (n_rows, n_ocean) float32."""
    vk = "vort_abs" if vort_mode == "abs" else "vort_cyc"
    keys = [vk, "conv", "sst", "sst_grad", "precip"]
    W = None
    for k, w in zip(keys, weights):
        if w == 0:
            continue
        a = C[k] if rows is None else C[k][rows]
        W = w * a if W is None else W + w * a
    if W is None:
        n = C["conv"].shape[1]
        nt = C["conv"].shape[0] if rows is None else len(np.atleast_1d(rows))
        W = np.zeros((nt, n), np.float32)
    return W


def mean_log1p_W(C, weights, vort_mode="abs", rows=None, chunk=400):
    """Time mean of log(1 + W) at ocean cells (memory-friendly chunks)."""
    nt = C["conv"].shape[0]
    rows = np.arange(nt) if rows is None else np.asarray(rows)
    acc = np.zeros(C["conv"].shape[1], np.float64)
    for s in range(0, len(rows), chunk):
        r = rows[s:s + chunk]
        acc += np.log1p(W_daily(C, weights, vort_mode, r)).sum(axis=0)
    return acc / len(rows)


def to_grid(vec_ocean, ocean_2d):
    """Map (n_ocean,) vector back to a 2-D field with NaN on land."""
    out = np.full(ocean_2d.shape, np.nan)
    out[ocean_2d] = vec_ocean
    return out


