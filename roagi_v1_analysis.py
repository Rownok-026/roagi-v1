def bilinear(field, plat, plon):
    """NaN-aware bilinear interpolation (land corners dropped, weights renormalized)."""
    la = lat[::-1]; f = field[::-1]
    i = np.clip(np.searchsorted(la, plat) - 1, 0, len(la) - 2)
    j = np.clip(np.searchsorted(lon, plon) - 1, 0, len(lon) - 2)
    ty = (plat - la[i]) / (la[i + 1] - la[i]); tx = (plon - lon[j]) / (lon[j + 1] - lon[j])
    v = np.stack([f[i, j], f[i, j + 1], f[i + 1, j], f[i + 1, j + 1]], -1)
    w = np.stack([(1 - ty) * (1 - tx), (1 - ty) * tx, ty * (1 - tx), ty * tx], -1)
    w = np.where(np.isfinite(v), w, 0.0); s = w.sum(-1)
    return np.where(s > 0, (np.nan_to_num(v) * w).sum(-1) / np.where(s > 0, s, 1), np.nan)

