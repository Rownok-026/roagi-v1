def auc_fast(pos, neg, presorted=False):
    """Mann-Whitney AUC = P(pos > neg) + 0.5 P(tie)."""
    pos = np.asarray(pos, float)
    neg = np.asarray(neg, float) if presorted else np.sort(np.asarray(neg, float))
    lo = np.searchsorted(neg, pos, "left")
    hi = np.searchsorted(neg, pos, "right")
    return float((lo + 0.5 * (hi - lo)).sum() / (len(pos) * len(neg)))


def auc_per_row(pos, neg_2d):
    return np.array([auc_fast(pos, r) for r in neg_2d])


def cohens_d(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    na, nb = len(a), len(b)
    sp = np.sqrt(((na - 1) * a.var(ddof=1) + (nb - 1) * b.var(ddof=1)) / (na + nb - 2))
    return float((a.mean() - b.mean()) / sp)


def block_ids(lat, lon, block_deg):
    return (np.floor(np.asarray(lat) / block_deg).astype(int) * 1000
            + np.floor(np.asarray(lon) / block_deg).astype(int))


def cluster_bootstrap_index(groups, n_boot, rng):
    """Yield index arrays from a cluster (block) bootstrap: clusters are
    resampled with replacement and all members of each drawn cluster kept."""
    groups = np.asarray(groups)
    uniq = np.unique(groups)
    members = {g: np.where(groups == g)[0] for g in uniq}
    for _ in range(n_boot):
        pick = rng.choice(uniq, size=len(uniq), replace=True)
        yield np.concatenate([members[g] for g in pick])


def bootstrap_auc_ci(g, bg_pooled, groups, n_boot, rng, alpha=0.05, extra=None):
    """CI for AUC (and mean difference) of genesis vs pooled background,
    resampling genesis points by cluster. If `extra` is given (second
    genesis-value array for the same points), the paired AUC difference
    AUC(g) - AUC(extra) is also bootstrapped (paired by point)."""
    bg_sorted = np.sort(bg_pooled)
    bg_mean = bg_pooled.mean()
    aucs, diffs, daucs = [], [], []
    for ix in cluster_bootstrap_index(groups, n_boot, rng):
        aucs.append(auc_fast(g[ix], bg_sorted, presorted=True))
        diffs.append(g[ix].mean() - bg_mean)
        if extra is not None:
            daucs.append(aucs[-1] - auc_fast(extra[0][ix], extra[1], presorted=True))
    q = [100 * alpha / 2, 100 * (1 - alpha / 2)]
    out = {"auc_ci": np.percentile(aucs, q), "diff_ci": np.percentile(diffs, q),
           "auc_boot": np.asarray(aucs)}
    if extra is not None:
        out["dauc_ci"] = np.percentile(daucs, q)
        out["dauc_boot"] = np.asarray(daucs)
    return out


def roc_points(pos, neg):
    """ROC curve (FPR, TPR) for scores where larger = genesis."""
    pos = np.asarray(pos, float)
    neg = np.asarray(neg, float)
    thr = np.unique(np.concatenate([pos, neg]))[::-1]
    ps, ns = np.sort(pos), np.sort(neg)
    tpr = 1 - np.searchsorted(ps, thr, "left") / len(ps)
    fpr = 1 - np.searchsorted(ns, thr, "left") / len(ns)
    return (np.concatenate([[0], fpr, [1]]), np.concatenate([[0], tpr, [1]]),
            np.concatenate([[np.inf], thr, [-np.inf]]))


def youden_threshold(pos, neg):
    fpr, tpr, thr = roc_points(pos, neg)
    k = int(np.argmax(tpr - fpr))
    return float(thr[k]), float(tpr[k]), float(fpr[k])


def perturb_one_weight(baseline, k, pct):
    """Change weight k by pct (e.g. +0.2) and rescale the others
    proportionally so that the weights still sum to 1 (original scheme)."""
    w = np.asarray(baseline, float).copy()
    new = w[k] * (1 + pct)
    others = [i for i in range(len(w)) if i != k]
    rest = 1.0 - new
    w[others] = w[others] / w[others].sum() * rest
    w[k] = new
    return np.clip(w, 0, None) / np.clip(w, 0, None).sum()


def haversine_km(lat1, lon1, lat2, lon2):
    p1, p2 = np.deg2rad(lat1), np.deg2rad(lat2)
    dl = np.deg2rad(np.asarray(lon2) - np.asarray(lon1))
    dp = p2 - p1
    a = np.sin(dp / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dl / 2) ** 2
    return 2 * RE_KM * np.arcsin(np.sqrt(np.clip(a, 0, 1)))

