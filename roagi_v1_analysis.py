def evaluate(field2d, full=True, extra_ref=None):
    """Genesis vs background statistics for one 2-D field."""
    g = S_GEN(field2d)
    B = S_BG(field2d).reshape(NB, N_G)
    pooled = B.ravel()
    out = dict(gen_mean=g.mean(), bg_mean=pooled.mean(), diff=g.mean() - pooled.mean(),
               auc=auc_fast(g, pooled), g=g, B=B)
    if not full:
        return out
    rep_means = B.mean(axis=1)
    out["p_mc_mean"] = (1 + np.sum(rep_means >= g.mean())) / (1 + NB)
    out["auc_draws"] = auc_per_row(g, B)
    out["cohen_d"] = cohens_d(g, pooled)
    out["cliff_delta"] = 2 * out["auc"] - 1
    rng = np.random.default_rng(CONFIG["seed"])
    for lab, grp in [("iid", np.arange(N_G)), ("year", G_YEAR_GROUPS), ("space", G_SPACE_GROUPS)]:
        bs = bootstrap_auc_ci(g, pooled, grp, CONFIG["n_boot"], rng, extra=extra_ref)
        out[f"auc_ci_{lab}"] = bs["auc_ci"]
        out[f"diff_ci_{lab}"] = bs["diff_ci"]
        out[f"p_boot_{lab}"] = min(1.0, 2 * np.mean(bs["auc_boot"] <= 0.5))
        if extra_ref is not None:
            out[f"dauc_ci_{lab}"] = bs["dauc_ci"]
    return out

