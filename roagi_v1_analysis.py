def sst_daily(dates):
    """Linear interpolation in time between (mid-month) SST stamps;
    dates before the first / after the last stamp take the nearest value."""
    t = pd.DatetimeIndex(dates).values.astype("datetime64[s]").astype(np.float64)
    s = SST_STAMPS.values.astype("datetime64[s]").astype(np.float64)
    i1 = np.clip(np.searchsorted(s, t), 1, len(s) - 1)
    i0 = i1 - 1
    a = np.clip((t - s[i0]) / (s[i1] - s[i0]), 0.0, 1.0)[:, None, None]
    return (1 - a) * SST_M[i0] + a * SST_M[i1]

