# 5. Coastal factor
# ------------------------------------------------------------
def coast_distance_km(grid_lat2d, grid_lon2d, coast_lonlat, method="great_circle"):
    """Distance (km) from each grid cell to the nearest coastline vertex.
    method='great_circle' : exact arc distance via 3-D chord KD-tree
    method='original'     : Euclidean distance in degrees x 111 (original code)"""
    pts = np.asarray(coast_lonlat, dtype=float)
    if method == "original":
        tree = cKDTree(pts)
        d, _ = tree.query(np.column_stack([grid_lon2d.ravel(), grid_lat2d.ravel()]))
        return (d * 111.0).reshape(grid_lat2d.shape)

    def xyz(lon, lat):
        la, lo = np.deg2rad(lat), np.deg2rad(lon)
        return np.column_stack([np.cos(la) * np.cos(lo), np.cos(la) * np.sin(lo), np.sin(la)])

    tree = cKDTree(xyz(pts[:, 0], pts[:, 1]))
    chord, _ = tree.query(xyz(grid_lon2d.ravel(), grid_lat2d.ravel()))
    arc = 2.0 * np.arcsin(np.clip(chord / 2.0, 0, 1)) * RE_KM
    return arc.reshape(grid_lat2d.shape)


def coastal_gaussian(dist_km, d0=400.0, sigma=200.0):
    """Published form: D = exp(-(d - d0)^2 / (2 sigma^2)); range (0, 1],
    maximum at d = d0."""
    return np.exp(-((dist_km - d0) ** 2) / (2.0 * sigma ** 2))


def coastal_monotonic(dist_km, L=100.0):
    """Alternative monotonic attenuation: D = 1 - exp(-d / L)."""
    return 1.0 - np.exp(-dist_km / L)


