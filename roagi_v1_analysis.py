import os, glob, subprocess
import numpy as np, pandas as pd
import matplotlib.pyplot as plt
from matplotlib import font_manager as fm

subprocess.run(["apt-get", "-qq", "install", "-y", "fonts-liberation"], capture_output=True)
for f in glob.glob("/usr/share/fonts/truetype/liberation*/*.ttf"):
    fm.fontManager.addfont(f)
plt.rcParams.update({"font.family": "serif", "font.serif": ["Times New Roman", "Liberation Serif"],
                     "font.size": 10, "axes.linewidth": 0.8,
                     "axes.spines.top": False, "axes.spines.right": False})

BASE = "/content/drive/MyDrive/JEOS ROWNOK/ROAGI_revision"
TAB = os.path.join(BASE, "tables"); OUT = os.path.join(BASE, "figures_publication"); os.makedirs(OUT, exist_ok=True)
oat = pd.read_csv(os.path.join(TAB, "TableS3a_weight_one_at_a_time.csv"))
mc = pd.read_csv(os.path.join(TAB, "TableS3b_weight_monte_carlo_all.csv"))
t3 = pd.read_csv(os.path.join(TAB, "Table3_validation_statistics.csv")).set_index("statistic")["value"]
AUC0 = float([v for k, v in t3.items() if "AUC vs pooled" in k][0])          # published weights

fig, (a, b) = plt.subplots(1, 2, figsize=(7.2, 3.3), layout="constrained")

# (a) one-at-a-time
cols = {"vorticity": "#2a78d6", "convergence": "#eb6834", "SST": "#1baf7a",
        "SST gradient": "#eda100", "precipitation": "#e87ba4"}
for comp, col in cols.items():
    s = oat[oat.component == comp].sort_values("change_pct")
    x = np.r_[s.change_pct.values[:3], 0, s.change_pct.values[3:]]
    yv = np.r_[s.AUC.values[:3], AUC0, s.AUC.values[3:]]
    a.plot(x, yv, marker="o", ms=4, lw=1.3, color=col, label=comp)
a.axhline(AUC0, color="#52514e", ls=":", lw=0.8)
a.set_xticks([-30, -20, -10, 0, 10, 20, 30])
a.set_xlabel("Change in one weight (%)"); a.set_ylabel("AUC")
a.legend(loc="best", frameon=True, framealpha=1, edgecolor="none", fontsize=8)
a.grid(alpha=0.25, lw=0.5)

# (b) random weight vectors
short = {"near-baseline (Dirichlet, concentration 20)": "Near-baseline weights",
         "unconstrained (uniform Dirichlet)": "Unconstrained weights"}
bins = np.linspace(mc.AUC.min(), mc.AUC.max(), 35)
for (lab, sdf), col in zip(mc.groupby("design"), ["#2a78d6", "#eb6834"]):
    b.hist(sdf.AUC, bins=bins, color=col, alpha=0.55, label=f"{short.get(lab, lab)} (n = {len(sdf)})")
b.axvline(AUC0, color="black", ls="--", lw=1.1, label=f"Published weights (AUC = {AUC0:.3f})")
b.set_xlabel("AUC"); b.set_ylabel("Number of weight vectors")
b.legend(loc="upper left", frameon=True, framealpha=1, edgecolor="none", fontsize=8)
b.grid(alpha=0.25, lw=0.5)

for ax, lab in ((a, "(a)"), (b, "(b)")):
    ax.text(0.0, 1.02, lab, transform=ax.transAxes, fontweight="bold", fontsize=11, va="bottom")

for ext in ("png", "tiff", "pdf"):
    kw = {"dpi": 1000, "bbox_inches": "tight"}
    if ext == "tiff":
        kw["pil_kwargs"] = {"compression": "tiff_lzw"}
    fig.savefig(os.path.join(OUT, f"FigS2_weight_sensitivity.{ext}"), **kw)
print("saved to", OUT)
