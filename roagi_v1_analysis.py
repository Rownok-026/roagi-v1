class PointSampler:
    def __init__(self, lat_grid, lon_grid, plat, plon):
        lat_grid, lon_grid = np.asarray(lat_grid, float), np.asarray(lon_grid, float)
        plat, plon = np.asarray(plat, float), np.asarray(plon, float)
        nlat, nlon = len(lat_grid), len(lon_grid)
        flip = lat_grid[0] > lat_grid[-1]
        la = lat_grid[::-1] if flip else lat_grid
        i = np.clip(np.searchsorted(la, plat) - 1, 0, nlat - 2)
        j = np.clip(np.searchsorted(lon_grid, plon) - 1, 0, nlon - 2)
        ty = (plat - la[i]) / (la[i + 1] - la[i]); tx = (plon - lon_grid[j]) / (lon_grid[j + 1] - lon_grid[j])
        inside = (plat >= la[0]) & (plat <= la[-1]) & (plon >= lon_grid[0]) & (plon <= lon_grid[-1])
        r0 = (nlat - 1 - i) if flip else i
        r1 = (nlat - 1 - (i + 1)) if flip else i + 1
        self.idx = np.stack([r0 * nlon + j, r0 * nlon + j + 1, r1 * nlon + j, r1 * nlon + j + 1], axis=-1)
        w = np.stack([(1 - ty) * (1 - tx), (1 - ty) * tx, ty * (1 - tx), ty * tx], axis=-1)
        w[~inside] = 0.0; self.w = w
    def __call__(self, f2d):
        v = np.asarray(f2d, float).ravel()[self.idx]
        ok = np.isfinite(v) & (self.w > 0); ww = np.where(ok, self.w, 0.0); s = ww.sum(-1)
        return np.where(s > 0, (np.where(ok, v, 0.0) * ww).sum(-1) / np.where(s > 0, s, 1.0), np.nan)

def draw_ocean_background(n_total, rng, lat_grid, lon_grid, ocean_2d, box):
    ocean_field = np.where(ocean_2d, 1.0, np.nan)
    lats, lons, got = [], [], 0
    while got < n_total:
        n = int((n_total - got) * 2) + 100
        s = rng.uniform(np.sin(np.deg2rad(box[0])), np.sin(np.deg2rad(box[1])), n)
        la, lo = np.rad2deg(np.arcsin(s)), rng.uniform(box[2], box[3], n)
        ok = np.isfinite(PointSampler(lat_grid, lon_grid, la, lo)(ocean_field))
        lats.append(la[ok]); lons.append(lo[ok]); got += int(ok.sum())
    return np.concatenate(lats)[:n_total], np.concatenate(lons)[:n_total]

def auc_fast(pos, neg):
    neg = np.sort(np.asarray(neg, float)); pos = np.asarray(pos, float)
    lo, hi = np.searchsorted(neg, pos, "left"), np.searchsorted(neg, pos, "right")
    return float((lo + 0.5 * (hi - lo)).sum() / (len(pos) * len(neg)))

def roc_points(pos, neg):
    thr = np.unique(np.concatenate([pos, neg]))[::-1]
    ps, ns = np.sort(pos), np.sort(neg)
    tpr = 1 - np.searchsorted(ps, thr, "left") / len(ps); fpr = 1 - np.searchsorted(ns, thr, "left") / len(ns)
    return np.r_[0, fpr, 1], np.r_[0, tpr, 1]

def coast_distance_km(lat2d, lon2d, pts):
    def xyz(lo, la):
        la, lo = np.deg2rad(la), np.deg2rad(lo)
        return np.column_stack([np.cos(la) * np.cos(lo), np.cos(la) * np.sin(lo), np.sin(la)])
    ch, _ = cKDTree(xyz(pts[:, 0], pts[:, 1])).query(xyz(lon2d.ravel(), lat2d.ravel()))
    return (2 * np.arcsin(np.clip(ch / 2, 0, 1)) * 6371.0).reshape(lat2d.shape)

