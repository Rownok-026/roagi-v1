# 7. NaN-aware bilinear sampling (precomputed weights)
# ------------------------------------------------------------
class PointSampler:
    """Bilinear interpolation of 2-D fields at fixed points.
    Corners that are NaN (land) are dropped and the remaining weights
    renormalized; a point is invalid when all four corners are NaN or it
    lies outside the grid."""

    def __init__(self, lat_grid, lon_grid, plat, plon):
        lat_grid = np.asarray(lat_grid, float)
        lon_grid = np.asarray(lon_grid, float)
        plat = np.asarray(plat, float)
        plon = np.asarray(plon, float)
        nlat, nlon = len(lat_grid), len(lon_grid)
        flip = lat_grid[0] > lat_grid[-1]
        la = lat_grid[::-1] if flip else lat_grid
        if lon_grid[0] > lon_grid[-1]:
            raise ValueError("Longitudes must be ascending.")
        i = np.clip(np.searchsorted(la, plat) - 1, 0, nlat - 2)
        j = np.clip(np.searchsorted(lon_grid, plon) - 1, 0, nlon - 2)
        ty = (plat - la[i]) / (la[i + 1] - la[i])
        tx = (plon - lon_grid[j]) / (lon_grid[j + 1] - lon_grid[j])
        inside = (plat >= la[0]) & (plat <= la[-1]) & (plon >= lon_grid[0]) & (plon <= lon_grid[-1])
        r0 = (nlat - 1 - i) if flip else i
        r1 = (nlat - 1 - (i + 1)) if flip else i + 1
        self.idx = np.stack([r0 * nlon + j, r0 * nlon + j + 1,
                             r1 * nlon + j, r1 * nlon + j + 1], axis=-1)
        w = np.stack([(1 - ty) * (1 - tx), (1 - ty) * tx, ty * (1 - tx), ty * tx], axis=-1)
        w[~inside] = 0.0
        self.w = w
        self.inside = inside

    def __call__(self, field2d):
        vals = np.asarray(field2d, float).ravel()[self.idx]
        ok = np.isfinite(vals) & (self.w > 0)
        ww = np.where(ok, self.w, 0.0)
        s = ww.sum(axis=-1)
        num = np.where(ok, vals, 0.0) * ww
        out = np.where(s > 0, num.sum(axis=-1) / np.where(s > 0, s, 1.0), np.nan)
        return out


def draw_equal_area_points(n, rng, lat_min, lat_max, lon_min, lon_max):
    """Uniform-by-area random points in a lat-lon box."""
    s = rng.uniform(np.sin(np.deg2rad(lat_min)), np.sin(np.deg2rad(lat_max)), n)
    return np.rad2deg(np.arcsin(s)), rng.uniform(lon_min, lon_max, n)


def draw_ocean_background(n_total, rng, lat_grid, lon_grid, ocean_2d, box):
    """Equal-area random points restricted to the ocean domain: a point is
    accepted when the NaN-aware bilinear interpolation of the ocean field is
    defined (same validity rule as applied to genesis points)."""
    ocean_field = np.where(ocean_2d, 1.0, np.nan)
    lats, lons, got = [], [], 0
    while got < n_total:
        la, lo = draw_equal_area_points(int((n_total - got) * 2) + 100, rng, *box)
        ok = np.isfinite(PointSampler(lat_grid, lon_grid, la, lo)(ocean_field))
        lats.append(la[ok])
        lons.append(lo[ok])
        got += int(ok.sum())
    return np.concatenate(lats)[:n_total], np.concatenate(lons)[:n_total]


