from scipy.spatial import cKDTree

RE_M = 6_371_000.0        # Earth radius (m)
RE_KM = 6_371.0


# ------------------------------------------------------------
# 1. Spherical finite differences (valid for ANY coordinate order)
# ------------------------------------------------------------
def grad_xy(f, lat_deg, lon_deg):
    """Centred finite differences of f on a regular lat-lon grid.

    f       : array (..., nlat, nlon)
    lat_deg : 1-D latitudes (ascending OR descending)
    lon_deg : 1-D longitudes
    returns (df/dx, df/dy) in [units of f] per metre.

    The signed coordinate arrays are passed to np.gradient, so the
    sign of d/dy is correct whether latitude runs N->S or S->N.
    """
    lat_r = np.deg2rad(np.asarray(lat_deg, dtype=float))
    lon_r = np.deg2rad(np.asarray(lon_deg, dtype=float))
    dfdy = np.gradient(f, lat_r, axis=-2) / RE_M
    dfdx = np.gradient(f, lon_r, axis=-1) / (RE_M * np.cos(lat_r))[:, None]
    return dfdx, dfdy


def original_vort_conv(u, v, lat_deg, lon_deg):
    """Exact replica of the ORIGINAL notebook's vorticity/convergence
    (absolute grid spacing, index-order gradients). Used only for the
    diagnostic comparison."""
    dlat = np.abs(lat_deg[1] - lat_deg[0]) * np.pi / 180
    dlon = np.abs(lon_deg[1] - lon_deg[0]) * np.pi / 180
    dy = dlat * RE_M
    dx = dlon * RE_M * np.cos(np.deg2rad(lat_deg))[:, None]
    du_dy = np.gradient(u, axis=-2) / dy
    dv_dx = np.gradient(v, axis=-1) / dx
    du_dx = np.gradient(u, axis=-1) / dx
    dv_dy = np.gradient(v, axis=-2) / dy
    return dv_dx - du_dy, -(du_dx + dv_dy)


# ------------------------------------------------------------
# 2. Nearest-valid filling (used before differencing SST)
# ------------------------------------------------------------
def nearest_fill_indices(nan_mask_2d):
    """Indices that map every cell to its nearest non-NaN cell."""
    _, idx = ndimage.distance_transform_edt(
        nan_mask_2d, return_distances=True, return_indices=True)
    return idx


def apply_nearest_fill(arr, idx):
    """arr (..., ny, nx); fills using indices from nearest_fill_indices."""
    return arr[..., idx[0], idx[1]]


# ------------------------------------------------------------
# 3. Daily raw components (corrected formulation)
# ------------------------------------------------------------
def daily_raw_components(u, v, tp, sst, lat_deg, lon_deg, sst_fill_idx):
    """u, v  : (nt, ny, nx) daily-mean 10-m winds (m s-1), unmasked
    tp     : (nt, ny, nx) daily precipitation (mm day-1)
    sst    : (nt, ny, nx) daily SST (deg C), may contain NaN on land
    sst_fill_idx : nearest-fill indices (SST is extended onto land ONLY so
                   that centred differences at coastal ocean cells are defined)
    returns dict of raw (un-normalized) fields, NOT yet masked."""
    dudx, dudy = grad_xy(u, lat_deg, lon_deg)
    dvdx, dvdy = grad_xy(v, lat_deg, lon_deg)
    zeta = dvdx - dudy                       # s-1, cyclonic > 0 (NH)
    conv = -(dudx + dvdy)                    # s-1, convergence > 0
    sst_f = sst if sst_fill_idx is None else apply_nearest_fill(sst, sst_fill_idx)
    dTdx, dTdy = grad_xy(sst_f, lat_deg, lon_deg)
    gradT = np.sqrt(dTdx ** 2 + dTdy ** 2) * 1.0e5   # K per 100 km
    return {
        "vort_abs": np.abs(zeta),
        "vort_cyc": np.maximum(zeta, 0.0),
        "conv": conv,
        "sst": sst_f,
        "sst_grad": gradT,
        "precip": tp,
        "_zeta": zeta,
    }


# ------------------------------------------------------------
# 4. Per-day min-max normalization over OCEAN cells only
# ------------------------------------------------------------
def minmax_ocean(X, ocean_2d):
    """X (nt, ny, nx). Each day is scaled to [0, 1] using the min and max
    over ocean cells of that day. Returns (nt, n_ocean) float32."""
    Xo = X[:, ocean_2d].astype(np.float64)          # (nt, n_ocean)
    mn = np.nanmin(Xo, axis=1, keepdims=True)
    mx = np.nanmax(Xo, axis=1, keepdims=True)
    rng = mx - mn
    out = np.where(rng > 0, (Xo - mn) / np.where(rng > 0, rng, 1.0), 0.0)
    return out.astype(np.float32)


